import assert from 'node:assert/strict'
import {test} from 'node:test'
import {readFileSync} from 'node:fs'

const read=(path:string)=>readFileSync(new URL('../../'+path,import.meta.url),'utf8')
const sql=read('supabase/migrations/20261113024454_event_document_ocr_review_audit.sql')
const api=read('frontend/src/app/api/events/[eventId]/documents/[documentId]/ocr-reviews/route.ts')
const handler=read('frontend/src/lib/server/event-document-ocr-review.ts')
const ui=read('frontend/src/components/sera/EventLocalOcrPreview.tsx')

test('OCR review table has RLS, no browser grants, FK chain to original and purge cascade',()=>{
  assert.match(sql,/ALTER TABLE public\.event_document_ocr_reviews ENABLE ROW LEVEL SECURITY/i)
  assert.match(sql,/REVOKE ALL ON TABLE public\.event_document_ocr_reviews FROM PUBLIC, anon, authenticated/i)
  assert.doesNotMatch(sql,/GRANT\s+(SELECT|INSERT|UPDATE|DELETE|ALL).*authenticated/i)
  assert.match(sql,/FOREIGN KEY \(tenant_id,event_id,document_id\)/)
  assert.match(sql,/REFERENCES public\.event_documents\(tenant_id,event_id,id\)/)
  assert.match(sql,/ON DELETE CASCADE/)
  assert.match(sql,/BEFORE UPDATE ON public\.event_document_ocr_reviews/i)
  assert.match(sql,/scientifically_validated boolean NOT NULL DEFAULT false CHECK \(scientifically_validated = false\)/)
  assert.match(sql,/analysis_changed boolean NOT NULL DEFAULT false CHECK \(analysis_changed = false\)/)
  assert.match(sql,/reviewer_auth_sha256/)
  assert.match(sql,/payload_sha256/)
})
test('bearer context drives tenant + reviewer; API no caller tenant or actor override',()=>{
  assert.match(api,/requireBearerUser\(req\)/)
  assert.match(api,/\['admin','analyst'\]/)
  assert.match(api,/tenantId:user\.tenantId/)
  assert.match(api,/authUserId:user\.authUserId/)
  assert.match(api,/publicUserId:user\.publicUserId/)
  assert.match(handler,/downloadAuthorizedEventDocument/)
  assert.match(handler,/listEventDocumentManifest/)
  assert.match(handler,/sha\(bytes\.bytes\)!==source\.sha256/)
  assert.match(handler,/MAX_REQUEST_BYTES=550_000/)
  assert.match(handler,/TOO_MANY_REVIEWS/)
  assert.doesNotMatch(api,/\.update\(|\.delete\(|(?:https?:\/\/)/)
  assert.doesNotMatch(handler,/from\('events'\)\.update|\.rpc\('sera/i)
})
test('confidential content remains server-only and UI clearly requires explicit save',()=>{
  assert.match(ui,/Salvar conferência no HFA/)
  assert.match(ui,/method:'POST'/)
  assert.match(ui,/JSON\.stringify\(localReview\)/)
  assert.match(ui,/res\.ok/)
  assert.match(ui,/data\.receipt\.persisted!==true/)
  assert.match(ui,/scientificallyValidated!==false/)
  assert.match(ui,/analysisChanged!==false/)
  assert.match(ui,/Histórico de conferências registradas/)
  assert.match(ui,/armazenamento confidencial no HFA/)
  assert.match(handler,/\.select\(columns\)/)
  assert.doesNotMatch(handler,/\.select\('ocr_text|\.select\('corrected_text/)
})
