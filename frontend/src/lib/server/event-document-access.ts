import { createHash } from 'node:crypto'
import type { SupabaseClient } from '@supabase/supabase-js'

export const EVENT_DOCUMENT_MAX_BYTES = 10 * 1024 * 1024
export const EVENT_DOCUMENT_BUCKET = 'analysis-documents'
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const MIME_TYPES = new Set([
  'application/pdf',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
])

export type EventDocumentInfo = {
  id: string
  fileName: string
  mimeType: string | null
  sizeBytes: number
  sourceOrdinal: number
  sha256: string | null
  createdAt: string
}

export class DocumentAccessError extends Error {
  constructor(
    public readonly code: 'NOT_FOUND' | 'INVALID_ID' | 'UNAVAILABLE' | 'INTEGRITY_MISMATCH',
  ) {
    super(code)
    this.name = 'DocumentAccessError'
  }
}

export const isEventDocumentId = (id: string) => UUID.test(id)

function fail(code: DocumentAccessError['code']): never {
  throw new DocumentAccessError(code)
}

async function assertEventAccessible(admin: SupabaseClient, tenantId: string, eventId: string) {
  if (!UUID.test(eventId)) fail('INVALID_ID')
  const { data, error } = await admin.from('events')
    .select('id')
    .eq('id', eventId)
    .eq('tenant_id', tenantId)
    .is('deleted_at', null)
    .neq('deletion_status', 'PURGED')
    .maybeSingle()
  if (error) fail('UNAVAILABLE')
  if (!data?.id) fail('NOT_FOUND')
}

/** No file path or private storage token leaks into the JSON manifest. */
export async function listEventDocumentManifest(
  admin: SupabaseClient,
  tenantId: string,
  eventId: string,
): Promise<EventDocumentInfo[]> {
  await assertEventAccessible(admin, tenantId, eventId)
  const { data, error } = await admin.from('event_documents')
    .select('id,file_name,mime_type,size_bytes,source_ordinal,content_sha256,created_at')
    .eq('tenant_id', tenantId)
    .eq('event_id', eventId)
    .order('source_ordinal', { ascending: true })
    .limit(5)
  if (error || !data) fail('UNAVAILABLE')
  return data.map((row) => ({
    id: String(row.id),
    fileName: String(row.file_name),
    mimeType: typeof row.mime_type === 'string' ? row.mime_type : null,
    sizeBytes: Number(row.size_bytes),
    sourceOrdinal: Number(row.source_ordinal),
    sha256: typeof row.content_sha256 === 'string' ? row.content_sha256 : null,
    createdAt: String(row.created_at),
  }))
}

type DownloadedDocument = {
  bytes: Uint8Array<ArrayBuffer>
  fileName: string
  mimeType: string
  hashVerified: boolean
}

/**
 * Always verify event and document tenant scoping BEFORE reading from the
 * service-role Storage client. Never use a user-provided storage path.
 */
export async function downloadAuthorizedEventDocument(
  admin: SupabaseClient,
  tenantId: string,
  eventId: string,
  documentId: string,
): Promise<DownloadedDocument> {
  if (!UUID.test(documentId)) fail('INVALID_ID')
  await assertEventAccessible(admin, tenantId, eventId)
  const { data: row, error } = await admin.from('event_documents')
    .select('file_name,mime_type,size_bytes,storage_path,content_sha256')
    .eq('id', documentId)
    .eq('tenant_id', tenantId)
    .eq('event_id', eventId)
    .maybeSingle()
  if (error) fail('UNAVAILABLE')
  if (!row) fail('NOT_FOUND')

  const mimeType = typeof row.mime_type === 'string' ? row.mime_type : ''
  const declaredSize = Number(row.size_bytes)
  const filePath = typeof row.storage_path === 'string' ? row.storage_path : ''
  const suffix = mimeType === 'application/pdf' ? 'pdf'
    : mimeType === 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' ? 'docx' : ''
  // Storage paths must be generated by the server under the requested event,
  // never supplied by request parameters or by a row referencing another event.
  const pathPattern = new RegExp(
    '^' + UUID.source.slice(1, -1) + '/events/' + eventId +
    '/' + UUID.source.slice(1, -1) + '[.]' + suffix + '$', 'i',
  )
  if (!MIME_TYPES.has(mimeType) || !suffix || !pathPattern.test(filePath) ||
      !Number.isSafeInteger(declaredSize) || declaredSize < 1 ||
      declaredSize > EVENT_DOCUMENT_MAX_BYTES) {
    fail('INTEGRITY_MISMATCH')
  }

  const { data: blob, error: storageError } = await admin.storage
    .from(EVENT_DOCUMENT_BUCKET).download(filePath)
  if (storageError || !blob) fail('UNAVAILABLE')
  if (blob.size !== declaredSize) fail('INTEGRITY_MISMATCH')
  const bytes = new Uint8Array(await blob.arrayBuffer())
  if (bytes.byteLength !== declaredSize) fail('INTEGRITY_MISMATCH')
  const hash = typeof row.content_sha256 === 'string' ? row.content_sha256 : null
  if (hash && createHash('sha256').update(bytes).digest('hex') !== hash) {
    fail('INTEGRITY_MISMATCH')
  }
  return {
    bytes,
    fileName: String(row.file_name),
    mimeType,
    hashVerified: hash !== null,
  }
}

/** Never allow CRLF, quotes, path separators or control characters in headers. */
export function safeDocumentContentDisposition(fileName: string): string {
  const base = fileName.split(/[\\/]/).pop() ?? 'document'
  const clean = base.replace(/[\x00-\x1f\x7f"<>]/g, '_').slice(0, 150) || 'document'
  const ascii = clean.replace(/[^\x20-\x7e]/g, '_').replace(/[\\]/g, '_')
  return 'attachment; filename="' + ascii + '"; filename*=UTF-8\x27\x27' +
    encodeURIComponent(clean).replace(/['()*]/g, (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase())
}
